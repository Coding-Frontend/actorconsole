import assert from "node:assert/strict";
import fs from "node:fs/promises";
import { chromium, expect } from "@playwright/test";
const browser = await chromium.launch({ executablePath: process.env.CHROMIUM_PATH ?? "/usr/bin/chromium", args: ["--no-sandbox"] });
const page = await browser.newPage();
const errors = [];
page.on("pageerror", (error) => errors.push(error.message));
await page.addInitScript(() => localStorage.setItem("actorconsole.cookie-consent", JSON.stringify({ version: 1, choice: "essential", timestamp: Date.now() })));
await page.route("**/*", (route) => new URL(route.request().url()).hostname === "127.0.0.1" ? route.continue() : route.abort("blockedbyclient"));
const origin = "http://127.0.0.1:4191";
const result = { pages: [], widths: [] };
result.pages.push({ path: "/docs/first-workspace", status: (await page.goto(`${origin}/docs/first-workspace`)).status() });
await page.getByRole("navigation", { name: "Breadcrumb" }).waitFor();
await page.evaluate(() => document.fonts.ready);
for (const width of [320, 375, 768, 1024, 1440]) {
  await page.setViewportSize({ width, height: 800 });
  const right = await page.getByRole("button", { name: "Search docs", exact: true }).evaluate((button) => button.getBoundingClientRect().right);
  assert.ok(right <= width);
  result.widths.push({ width, searchRight: right });
}
await page.getByRole("button", { name: "Search docs", exact: true }).click();
await expect(page.getByRole("searchbox")).toBeFocused();
await page.keyboard.press("Escape");
await expect(page.getByRole("button", { name: "Search docs", exact: true })).toBeFocused();
const payloads = [];
await page.route("**/api/auth/local/login", async (route) => {
  payloads.push(route.request().postDataJSON());
  await route.fulfill({ json: { ok: true, requiresTwoFactor: true, challengeToken: "disposable-challenge" } });
});
result.pages.push({ path: "/login", status: (await page.goto(`${origin}/login`)).status() });
await page.getByLabel("Email", { exact: true }).fill("audit@example.com");
await page.getByLabel("Password", { exact: true }).fill("disposable-password");
await page.getByRole("button", { name: "Sign in with email" }).click();
await expect(page.getByLabel("Authenticator code")).toBeFocused();
await page.getByLabel("Authenticator code").fill("123456");
await page.getByLabel("Authenticator code").press("Enter");
await expect.poll(() => payloads.length).toBe(2);
assert.equal(payloads[1].totpCode, "123456");
assert.equal(payloads[1].challengeToken, "disposable-challenge");
result.keyboardVerification = true;
await page.route("**/api/auth/local/login", (route) => route.abort("failed"));
await page.getByRole("button", { name: "Verify and continue" }).click();
await expect(page.getByRole("main").getByRole("alert")).toContainText("Failed to fetch");
assert.equal(errors.length, 0);
let finish;
await page.route("**/api/contact", async (route) => {
  await new Promise((resolve) => { finish = resolve; });
  await route.fulfill({ json: { ok: true } });
});
result.pages.push({ path: "/contact", status: (await page.goto(`${origin}/contact`)).status() });
await page.getByLabel("Full Name").fill("Local audit");
await page.getByLabel("Email Address").fill("audit@example.com");
await page.getByLabel("Message").fill("Original message locally mocked");
await page.getByRole("button", { name: "Send Message" }).click();
await expect.poll(() => Boolean(finish)).toBe(true);
await page.getByLabel("Message").fill("New unsent draft");
finish();
await expect(page.getByRole("button", { name: "Send Message" })).toBeEnabled();
await expect(page.getByLabel("Message")).toHaveValue("New unsent draft");
result.contactPreservesNewDraft = true;
result.pageErrors = errors;
assert.ok(result.pages.every((entry) => entry.status === 200));
await fs.writeFile("/tmp/ui-implementation-next.json", `${JSON.stringify(result, null, 2)}\n`);
process.stdout.write(`${JSON.stringify(result, null, 2)}\n`);
await browser.close();
