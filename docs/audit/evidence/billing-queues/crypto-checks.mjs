import assert from 'node:assert/strict';
import { createRequire } from 'node:module';
import { createHmac } from 'node:crypto';
import { verifyRazorpaySignature } from '/workspace/actorconsole/packages/shared/dist/razorpay.js';
const require=createRequire('/workspace/actorconsole/package.json');
const Stripe=require('stripe'); const Dodo=require('dodopayments').default;
const { Webhook }=require('standardwebhooks');
const raw=JSON.stringify({ id:'evt_fixture',type:'unhandled',data:{object:{}} });
const secret='fixture-only-placeholder';
const sig=createHmac('sha256',secret).update(raw).digest('hex');
assert.equal(verifyRazorpaySignature(raw,sig,secret),true);
assert.equal(verifyRazorpaySignature(raw+' ',sig,secret),false);
assert.equal(verifyRazorpaySignature(raw,undefined,secret),false);
const stripe=new Stripe('sk_test_fixture');
const stripeHeader=stripe.webhooks.generateTestHeaderString({ payload:raw,secret });
assert.equal(stripe.webhooks.constructEvent(raw,stripeHeader,secret).id,'evt_fixture');
assert.throws(()=>stripe.webhooks.constructEvent(raw+' ',stripeHeader,secret));
const oldHeader=stripe.webhooks.generateTestHeaderString({ payload:raw,secret,timestamp:Math.floor(Date.now()/1000)-600 });
assert.throws(()=>stripe.webhooks.constructEvent(raw,oldHeader,secret));
const webhookKey='whsec_'+Buffer.from('fixture-only-signing-material').toString('base64');
const wh=new Webhook(webhookKey); const now=new Date();
const headers={'webhook-id':'evt_fixture','webhook-timestamp':String(Math.floor(now.getTime()/1000)),'webhook-signature':wh.sign('evt_fixture',now,raw)};
const dodo=new Dodo({ bearerToken:'fixture',webhookKey });
assert.equal(dodo.webhooks.unwrap(raw,{headers}).id,'evt_fixture');
assert.throws(()=>dodo.webhooks.unwrap(raw+' ',{headers}));
assert.throws(()=>dodo.webhooks.unwrap(raw,{headers:{}}));
const old=new Date(now.getTime()-600000);
assert.throws(()=>dodo.webhooks.unwrap(raw,{headers:{...headers,'webhook-timestamp':String(Math.floor(old.getTime()/1000)),'webhook-signature':wh.sign('evt_fixture',old,raw)}}));
process.stdout.write('10 local cryptographic assertions passed; no provider requests.\n');
