-- Persist the public Apify Store independently from workspace-owned Actors.

CREATE TABLE `StoreActor` (
  `id` VARCHAR(191) NOT NULL,
  `apifyActorId` VARCHAR(191) NOT NULL,
  `username` VARCHAR(191) NOT NULL,
  `actorName` VARCHAR(191) NOT NULL,
  `title` VARCHAR(191) NULL,
  `description` TEXT NULL,
  `pictureUrl` TEXT NULL,
  `ownerName` VARCHAR(191) NULL,
  `ownerPictureUrl` TEXT NULL,
  `isPublic` BOOLEAN NOT NULL DEFAULT true,
  `isDeprecated` BOOLEAN NOT NULL DEFAULT false,
  `apifyCreatedAt` DATETIME(3) NULL,
  `firstPublishedAt` DATETIME(3) NULL,
  `apifyModifiedAt` DATETIME(3) NULL,
  `totalRuns` INTEGER NULL,
  `totalUsers` INTEGER NULL,
  `users7Days` INTEGER NULL,
  `users30Days` INTEGER NULL,
  `users90Days` INTEGER NULL,
  `runs30Days` INTEGER NULL,
  `reviewCount` INTEGER NULL,
  `reviewRating` DOUBLE NULL,
  `bookmarkCount` INTEGER NULL,
  `categories` JSON NULL,
  `metaLabels` JSON NULL,
  `pricingInfos` JSON NULL,
  `firstSeenAt` DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3),
  `lastSeenAt` DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3),
  `detailsSyncedAt` DATETIME(3) NULL,
  `detailsSyncError` TEXT NULL,
  `createdAt` DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3),
  `updatedAt` DATETIME(3) NOT NULL,
  UNIQUE INDEX `StoreActor_apifyActorId_key` (`apifyActorId`),
  INDEX `StoreActor_username_idx` (`username`),
  INDEX `StoreActor_users30Days_idx` (`users30Days`),
  INDEX `StoreActor_firstPublishedAt_idx` (`firstPublishedAt`),
  INDEX `StoreActor_lastSeenAt_idx` (`lastSeenAt`),
  INDEX `StoreActor_detailsSyncedAt_idx` (`detailsSyncedAt`),
  PRIMARY KEY (`id`)
) DEFAULT CHARACTER SET utf8mb4 COLLATE utf8mb4_unicode_ci;

CREATE TABLE `StoreActorSnapshot` (
  `id` VARCHAR(191) NOT NULL,
  `storeActorId` VARCHAR(191) NOT NULL,
  `capturedAt` DATETIME(3) NOT NULL,
  `totalRuns` INTEGER NULL,
  `totalUsers` INTEGER NULL,
  `users30Days` INTEGER NULL,
  `runs30Days` INTEGER NULL,
  `reviewCount` INTEGER NULL,
  `reviewRating` DOUBLE NULL,
  UNIQUE INDEX `StoreActorSnapshot_storeActorId_capturedAt_key` (`storeActorId`, `capturedAt`),
  INDEX `StoreActorSnapshot_storeActorId_capturedAt_idx` (`storeActorId`, `capturedAt`),
  PRIMARY KEY (`id`),
  CONSTRAINT `StoreActorSnapshot_storeActorId_fkey` FOREIGN KEY (`storeActorId`) REFERENCES `StoreActor`(`id`) ON DELETE CASCADE ON UPDATE CASCADE
) DEFAULT CHARACTER SET utf8mb4 COLLATE utf8mb4_unicode_ci;

CREATE TABLE `StoreCatalogSync` (
  `id` VARCHAR(191) NOT NULL,
  `operation` VARCHAR(191) NOT NULL,
  `status` VARCHAR(191) NOT NULL,
  `expectedCount` INTEGER NULL,
  `processedCount` INTEGER NOT NULL DEFAULT 0,
  `createdCount` INTEGER NOT NULL DEFAULT 0,
  `updatedCount` INTEGER NOT NULL DEFAULT 0,
  `error` TEXT NULL,
  `startedAt` DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3),
  `completedAt` DATETIME(3) NULL,
  INDEX `StoreCatalogSync_operation_startedAt_idx` (`operation`, `startedAt`),
  INDEX `StoreCatalogSync_status_startedAt_idx` (`status`, `startedAt`),
  PRIMARY KEY (`id`)
) DEFAULT CHARACTER SET utf8mb4 COLLATE utf8mb4_unicode_ci;
